FLAGS_A:
    MOVI R1 0
    CMPI R1 0
    JNZ ERROR_A

    JMP FLAGS_A

ERROR_A:
    STINTI 00000000
    MOVI R2 10
    PRINT R2
    GF R1
    PRINT R1
    JMP UNDER_ERROR

UNDER_ERROR:
    JMP UNDER_ERROR

ERROR_B:
    STINTI 00000000
    MOVI R2 100
    PRINT R2
    GF R1
    PRINT R1
    JMP UNDER_ERROR

FLAGS_B:
    MOVI R1 1
    CMPI R1 0
    JNC ERROR_B
    JMP FLAGS_B