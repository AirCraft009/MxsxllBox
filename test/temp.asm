JMP REDRAW_SCREEN

MOVI O3 0
MOVI R3 0

REDRAW_SCREEN:
    MOV R1 O1
    MOV R2 O2
    CALL _setP_xy
    MOV O1 R1
    MOV O2 R2
    MOV O3 R3
    ADDI O1 1
    CMPI O1 256
    JZ NEWLINE
    JMP REDRAW_SCREEN




NEWLINE:
    CMPI O2 256
    JZ END
    MOVI O1 0
    ADDI O2 1
    JMP REDRAW_SCREEN

END:
    MOVI O1 0
    MOVI O2 0
    CMPI O3 1
    JZ SWITCH_BLACK
    MOVI O3 1
    MOVI R3 1
    JMP REDRAW_SCREEN

SWITCH_BLACK:
    MOVI R3 0
    MOVI O3 0
    JMP REDRAW_SCREEN
